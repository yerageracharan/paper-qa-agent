#!/usr/bin/env bash
# Regenerates docs/demo.md from real CLI runs (offline backend). Usage: bash scripts/make_demo.sh
set -euo pipefail
cd "$(dirname "$0")/.."
{
echo '# Demo transcript'; echo
echo 'Real output from the offline backend (extractive answerer, LSA embeddings) on the bundled synthetic paper. Generated by `scripts/make_demo.sh`; nothing here is hand-edited.'; echo
for q in "What bottleneck dimension do the adapters use?" "By what percentage does SGA cut training time?" "Which layers keep their adapters according to the learned gates?" "What was the carbon footprint of the experiments?" "What macro-F1 does LoRA achieve on FoodReviews?" "Did the authors run a human evaluation?"; do
  echo '```'; echo "\$ python -m paperqa ask data/sample_paper.pdf \"$q\""; python -m paperqa ask data/sample_paper.pdf "$q" --llm extractive; echo '```'; echo
done
} > docs/demo.md
